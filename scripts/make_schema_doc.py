def main():
    path = ROOT / "docs" / "SCHEMA.md"
    path.parent.mkdir(exist_ok=True)
    tmp = ROOT / "data" / "schema_doc.db"
    tmp.unlink(missing_ok=True)
    version = storage.init_db(tmp)
    c = sqlite3.connect(tmp)
    out = [f"# Database schema (SQLite, version {version})", "",
           "Generated by `scripts/make_schema_doc.py` from the migrations in `eb_app/storage.py`. Nothing is ever written to Oracle EBS.", ""]
    tables = [r[0] for r in c.execute("select name from sqlite_master where type='table' and name like 'electricity_%' order by name")]
    out += ["| Table | Purpose |", "|---|---|"] + [f"| `{t}` | {PURPOSE.get(t, '')} |" for t in tables] + [""]
    for t in tables:
        out += [f"## {t}", "", PURPOSE.get(t, ""), "", "| Column | Type | Null | Default | Key |", "|---|---|---|---|---|"]
        fks = {r[3]: f"-> {r[2]}({r[4]})" for r in c.execute(f"pragma foreign_key_list({t})")}
        for cid, name, typ, notnull, dflt, pk in c.execute(f"pragma table_info({t})"):
            key = "PK" if pk else fks.get(name, "")
            out.append(f"| {name} | {typ} | {'NOT NULL' if notnull else ''} | {'' if dflt is None else dflt} | {key} |")
        idx = [(r[1], r[2]) for r in c.execute(f"pragma index_list({t})")]
        if idx:
            out += ["", "Indexes / unique constraints: " + ", ".join(f"`{n}`{' (unique)' if u else ''}" for n, u in idx)]
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")
    c.close()
    tmp.unlink(missing_ok=True)
    print("wrote", path, len(tables), "tables")


if __name__ == "__main__":
    main()
